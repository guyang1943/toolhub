/**
 * 搜索口语词表（v3.11）：把用户嘴里的词，映射到工具名/标签里实际存在的词
 *
 * 为什么要有这个：
 *   站内搜索是子串匹配，匹配的是工具名、标签、别名。但用户不按工具名说话——
 *   想压缩图片的人打「瘦身」，想拆 PDF 的人打「拆开」，想处理照片的人打「照片」。
 *   这些词在 99 个工具的元数据里一个都不存在，搜索就必然空手而归。
 *
 * 为什么放在构建期而不是运行时：
 *   aliases 本来就是 scripts/gen-search-aliases.mjs 在构建期写进 JSON 的（拼音就是这么来的）。
 *   词表并进别名之后，运行时一行代码都不用加，首屏预算零增长，工具数量涨了也只是重跑生成器。
 *
 * 约束（由 scripts/verify.mjs 把关，写错会直接红）：
 *   1. 每个主词必须是某个工具的名字或标签的子串，否则这条映射永远不会生效——那是死配置
 *   2. 每个变体必须真的出现在工具 aliases 里，否则说明改了词表忘了重跑生成器
 *   3. 变体只做「同义」，不做「相关」：「视频」不该被映射到「图片」，那会把搜索变糊
 */
export const SPOKEN = {
  // —— 文件与图片 ——
  压缩: ['瘦身', '压小', '变小', '减体积', '太大了'],
  格式转换: ['转格式', '换格式', '另存为'],
  转换: ['转格式', '换格式', '转成'],
  合并: ['拼起来', '合起来', '合成一个', '连起来'],
  拆分: ['拆开', '切开', '一分为二', '分成两个'],
  图片: ['照片', '截图', '图像'],
  二维码: ['扫码', 'qr码', '二维码图片'],
  裁剪: ['裁切', '切图', '剪切'],
  缩放: ['改尺寸', '调大小', '放大', '缩小'],
  去重: ['重复项', '删除重复', '去重复'],
  字数: ['多少字', '字数多少', '数一下字'],
  文字识别: ['提取文字', '图片转文字', '认字'],
  转码: ['视频转换', '视频压缩'],
  传文件: ['发文件', '传东西', '传输文件'],

  // —— 编码与安全 ——
  密码: ['口令', '随机密码'],
  校验: ['验证', '检查格式', '对不对'],
  哈希: ['摘要', '指纹', '校验值'],
  加密: ['加密码', '设置密码'],

  // —— 效率与绘图 ——
  白板: ['画板', '画图板', '手绘'],
  思维导图: ['脑图', '导图'],
  流程图: ['流程'],
  颜色: ['配色', '色值', '色号'],
  对比: ['比对', '差异', 'diff'],
  正则: ['regexp', '规则匹配'],
  单位: ['度量衡', '换算'],

  // —— 计算器 ——
  房贷: ['月供', '贷款计算'],
  个税: ['扣税', '到手工资', '税后'],
};

/** 一个工具（按名字 + 标签）应该额外带上的口语别名 */
export function spokenAliases(name, tags) {
  const text = String(name || '') + ' ' + (tags || []).join(' ');
  const out = [];
  for (const [canon, variants] of Object.entries(SPOKEN)) {
    if (text.includes(canon)) out.push(...variants);
  }
  return out;
}

/** 词表里所有变体（供校验脚本比对） */
export function allVariants() {
  return Object.values(SPOKEN).flat();
}
